import { Hono } from 'hono';
import type {
  OnAppInstallRequest,
  OnModMailRequest,
  TriggerResponse,
} from '@devvit/web/shared';
import { reddit } from '@devvit/web/server';
import { dispatchModMailCommand } from '../features/modmail-commands/commands.js';

// Router for trigger endpoints declared in devvit.json/triggers.
export const triggers = new Hono();

triggers.post('/on-app-install', async (c) => {
  // Parse install trigger payload.
  const input = await c.req.json<OnAppInstallRequest>();
  console.log('App installed to subreddit: r/' + input.subreddit?.name);

  return c.json<TriggerResponse>(
    {
      status: 'success',
    },
    200
  );
});

triggers.post('/on-modmail', async (c) => {
  const input = await c.req.json<OnModMailRequest>();


  // Only process messages written by a moderator.
  if (
    input.messageAuthorType !== 'ParticipatingAs_MODERATOR' ||
    input.isAutoGenerated
  ) {
    return c.json<TriggerResponse>({ status: 'success' }, 200);
  }

  try {
    const result = await reddit.modMail.getConversation({
      conversationId: input.conversationId,
    });

    const conversation = result.conversation;

    if (!conversation) {
      console.error('Could not retrieve Modmail conversation');
      return c.json<TriggerResponse>({ status: 'success' }, 200);
    }

    const messageId = input.messageId.split('_').pop()!;

    const message =
      conversation.messages[messageId] ??
      Object.values(conversation.messages).find(
        (item) => item.id === messageId
      );

    if (!message || !message.isInternal) {
      return c.json<TriggerResponse>({ status: 'success' }, 200);
    }

    const body = message.bodyMarkdown ?? message.body ?? '';
    const parts = body.trim().split(/\s+/);

    if (!parts[0]?.startsWith('!')) {
      return c.json<TriggerResponse>({ status: 'success' }, 200);
    }

    const command = parts[0].slice(1).toLowerCase();
    const args = parts.slice(1);

  const conversationUser = result.user as
    | { name?: string; username?: string }
    | undefined;

    await dispatchModMailCommand(command, args, {
      subredditName: input.conversationSubreddit?.name ?? 'unknown',
      conversationId: input.conversationId,
      respond: async (message) => {
        await reddit.modMail.reply({
          conversationId: input.conversationId,
          body: message,
          isInternal: true,
        });
      },
      createdBy: message.author?.name ?? 'unknown',
      conversationUser: conversationUser?.username ?? 'unknown',
    });
  } catch (error) {
    console.error(
      `[modmail-command] Failed to process conversation ${input.conversationId}:`,
      error
    );
  }

  return c.json<TriggerResponse>({ status: 'success' }, 200);
});